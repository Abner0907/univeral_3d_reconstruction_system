// u3d_fake_ns - a tiny stand-in for the Nerfstudio CLI.
//
// Usage: u3d_fake_ns <ns-process-data|ns-train|ns-export> <same arguments as the real tool>
//
// It prints console output shaped like Nerfstudio's (so progress parsing is exercised) and
// writes small but valid outputs: transforms.json, config.yml and a coloured-sphere .ply
// (Gaussian-splat layout for splatfacto, RGB point cloud for nerfacto). This lets the whole
// system - desktop app, server, Android app, CI - run without a GPU.
//
// Environment:
//   U3D_FAKE_STEP_DELAY  seconds per simulated step (default 0.05)
//   U3D_FAKE_FAIL_STAGE  process-data | train | export -> exit with an error in that stage

#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <iterator>
#include <string>
#include <thread>
#include <vector>

namespace fs = std::filesystem;

namespace {

constexpr double kPi = 3.14159265358979323846;
constexpr float kShC0 = 0.28209479177387814f;

std::string arg(const std::vector<std::string> &args, const std::string &name, const std::string &fallback)
{
    for (std::size_t i = 0; i + 1 < args.size(); ++i)
        if (args[i] == name)
            return args[i + 1];
    return fallback;
}

void stepDelay()
{
    const char *env = std::getenv("U3D_FAKE_STEP_DELAY");
    const double seconds = env ? std::atof(env) : 0.05;
    std::this_thread::sleep_for(std::chrono::milliseconds(static_cast<int>(seconds * 1000.0)));
}

void maybeFail(const std::string &stage)
{
    const char *env = std::getenv("U3D_FAKE_FAIL_STAGE");
    if (env && stage == env) {
        std::cout << "[fake] simulated failure in " << stage << std::endl;
        std::exit(3);
    }
}

template <typename T>
void writeLE(std::ofstream &out, T value)
{
    // All supported build targets are little endian; PLY header declares binary_little_endian.
    out.write(reinterpret_cast<const char *>(&value), sizeof(T));
}

void writeSpherePly(const fs::path &path, bool splat)
{
    const int n = 4000;
    std::ofstream out(path, std::ios::binary);
    out << "ply\nformat binary_little_endian 1.0\n";
    out << "comment generated by u3d_fake_ns\n";
    out << "element vertex " << n << "\n";
    out << "property float x\nproperty float y\nproperty float z\n";
    if (splat) {
        for (const char *p : {"f_dc_0", "f_dc_1", "f_dc_2", "opacity", "scale_0", "scale_1",
                              "scale_2", "rot_0", "rot_1", "rot_2", "rot_3"})
            out << "property float " << p << "\n";
    } else {
        out << "property uchar red\nproperty uchar green\nproperty uchar blue\n";
    }
    out << "end_header\n";

    const double golden = kPi * (3.0 - std::sqrt(5.0));
    for (int i = 0; i < n; ++i) {
        const double y = 1.0 - (double(i) / (n - 1)) * 2.0;
        const double r = std::sqrt(std::max(0.0, 1.0 - y * y));
        const double theta = golden * i;
        const float px = float(std::cos(theta) * r), py = float(y), pz = float(std::sin(theta) * r);
        const float cr = (px + 1.f) / 2.f, cg = (py + 1.f) / 2.f, cb = (pz + 1.f) / 2.f;
        writeLE(out, px);
        writeLE(out, py);
        writeLE(out, pz);
        if (splat) {
            for (float c : {cr, cg, cb})
                writeLE(out, (c - 0.5f) / kShC0);
            writeLE(out, 4.0f); // opacity logit
            for (float s : {-4.0f, -4.0f, -4.0f, 1.0f, 0.0f, 0.0f, 0.0f})
                writeLE(out, s);
        } else {
            for (float c : {cr, cg, cb})
                writeLE(out, static_cast<std::uint8_t>(c * 255.0f));
        }
    }
}

int processData(const std::vector<std::string> &args)
{
    const fs::path outDir = arg(args, "--output-dir", "processed");
    const fs::path data = arg(args, "--data", ".");
    fs::create_directories(outDir);
    std::size_t count = 1;
    if (fs::is_directory(data))
        count = static_cast<std::size_t>(std::distance(fs::directory_iterator(data), fs::directory_iterator()));
    for (const char *stage : {"Copying images", "Extracting features", "Matching features", "Bundle adjustment"}) {
        std::cout << "[fake] " << stage << "..." << std::endl;
        stepDelay();
    }
    maybeFail("process-data");
    std::ofstream(outDir / "transforms.json") << "{\"frames\": []}\n";
    std::cout << "[fake] Processed " << count << " input(s) with COLMAP" << std::endl;
    return 0;
}

int train(const std::vector<std::string> &args)
{
    if (args.empty())
        return 2;
    const std::string method = args[0];
    const fs::path outputs = arg(args, "--output-dir", "outputs");
    const std::string experiment = arg(args, "--experiment-name", "experiment");
    const std::string timestamp = arg(args, "--timestamp", "run");
    const long maxIter = std::atol(arg(args, "--max-num-iterations", "30000").c_str());
    const fs::path runDir = outputs / experiment / method / timestamp;
    fs::create_directories(runDir);

    std::cout << "Step (% Done)       Train Iter (time)    ETA (time)" << std::endl;
    std::cout << "------------------------------------------------------------" << std::endl;
    const int ticks = 20;
    for (int t = 1; t <= ticks; ++t) {
        const long step = maxIter * t / ticks;
        const double pct = 100.0 * t / ticks;
        char line[128];
        std::snprintf(line, sizeof line, "%-10ld (%.2f%%)       12.345 ms            1 m, 2 s", step, pct);
        std::cout << line << std::endl;
        stepDelay();
        if (t == ticks / 2)
            maybeFail("train");
    }
    std::ofstream(runDir / "config.yml") << "method_name: " << method << "\n";
    std::cout << "[fake] Saved config to " << (runDir / "config.yml").string() << std::endl;
    return 0;
}

int exportResult(const std::vector<std::string> &args)
{
    if (args.empty())
        return 2;
    const std::string kind = args[0];
    const fs::path outDir = arg(args, "--output-dir", "exports");
    fs::create_directories(outDir);
    std::cout << "[fake] Exporting " << kind << "..." << std::endl;
    stepDelay();
    maybeFail("export");
    if (kind == "gaussian-splat")
        writeSpherePly(outDir / "splat.ply", true);
    else
        writeSpherePly(outDir / "point_cloud.ply", false);
    std::cout << "[fake] Export complete" << std::endl;
    return 0;
}

} // namespace

int main(int argc, char **argv)
{
    if (argc < 2) {
        std::cerr << "usage: u3d_fake_ns <ns-process-data|ns-train|ns-export> [args...]\n";
        return 2;
    }
    const std::string tool = argv[1];
    std::vector<std::string> args(argv + 2, argv + argc);
    try {
        if (tool == "ns-process-data")
            return processData(std::vector<std::string>(args.begin() + (args.empty() ? 0 : 1), args.end()));
        if (tool == "ns-train")
            return train(args);
        if (tool == "ns-export")
            return exportResult(args);
    } catch (const std::exception &e) {
        std::cerr << "[fake] error: " << e.what() << std::endl;
        return 1;
    }
    std::cerr << "unknown tool: " << tool << "\n";
    return 2;
}
